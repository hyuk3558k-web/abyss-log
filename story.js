function missionTheme(m) {
  const R = REGIONS[m.r], T = Object.assign({}, R.theme);
  if (T.kind === 'mountain' || T.kind === 'village') {
    const S = SKIES[m.time === 'cave' ? 'night' : m.time] || SKIES.day;
    Object.assign(T, { sky: S, fog: S.fog, fogD: S.fogD, amb: S.amb, light: S.sun });
  }
  return T;
}

